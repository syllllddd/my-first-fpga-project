`timescale 1ns / 1ps
//=============================================================================
// rgb2gray : RGB444 -> 灰度 (亮度 Y = 0.299R + 0.587G + 0.114B)
//   该 Y 即 YCbCr 色彩空间的亮度分量, 定点系数 77/256, 150/256, 29/256
//=============================================================================
module rgb2gray (
    input  wire [3:0] r,
    input  wire [3:0] g,
    input  wire [3:0] b,
    output wire [7:0] gray
);
    // 4bit -> 8bit (复制拼接: 0..15 -> 0..255)
    wire [7:0] r8 = {r, r};
    wire [7:0] g8 = {g, g};
    wire [7:0] b8 = {b, b};

    // 定点乘法: Y = (77*R + 150*G + 29*B) / 256, 结果 0..255
    wire [15:0] sum = 8'd77 * r8 + 8'd150 * g8 + 8'd29 * b8;
    assign gray = sum[15:8];
endmodule
